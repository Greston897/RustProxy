//! Таблица версий протоколов и их идентификаторов пакетов.
//!
//! Покрывает диапазон 754 (1.16.5) → 777 (26.3, 2026).

use crate::protocol::versions::{version_name, is_supported as is_protocol_supported};

/// Идентификатор протокола Minecraft.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ProtocolVersionId(pub i32);

impl ProtocolVersionId {
    pub fn is_supported(self) -> bool {
        is_protocol_supported(self.0)
    }

    pub fn name(self) -> &'static str {
        version_name(self.0)
    }
}

/// Информация о версии: ID пакетов для Handshaking, Status, Login, Play.
pub struct ProtocolVersion {
    pub id: ProtocolVersionId,
    /// Имя версии (например "1.16.5", "26.3")
    pub name: &'static str,
    /// Пакеты Handshaking (serverbound)
    pub handshake_id: i32,
    /// Пакеты Status
    pub status_request_id: i32,
    pub status_response_id: i32,
    pub status_ping_id: i32,
    pub status_pong_id: i32,
    /// Пакеты Login (serverbound)
    pub login_start_id: i32,
    pub login_encryption_begin_id: i32,
    /// Пакеты Login (clientbound)
    pub login_disconnect_id: i32,
    pub login_encryption_request_id: i32,
    pub login_success_id: i32,
    pub login_set_compression_id: i32,
    /// Пакеты Play (serverbound)
    pub play_chat_message_id: i32,
    pub play_player_position_id: i32,
    pub play_player_look_id: i32,
    pub play_player_position_and_look_id: i32,
    pub play_player_on_ground_id: i32,
    pub play_keep_alive_id: i32,
    pub play_teleport_confirm_id: i32,
    /// Пакеты Play (clientbound)
    pub play_join_game_id: i32,
    pub play_spawn_position_id: i32,
    pub play_player_position_and_look_cb_id: i32,
    pub play_chat_message_cb_id: i32,
    pub play_disconnect_id: i32,
    pub play_keep_alive_cb_id: i32,
    pub play_spawn_object_id: i32,
    pub play_spawn_mob_id: i32,
    pub play_spawn_player_id: i32,
    pub play_entity_metadata_id: i32,
    pub play_entity_velocity_id: i32,
    pub play_entity_position_id: i32,
    pub play_entity_look_id: i32,
    pub play_entity_position_and_look_id: i32,
    pub play_entity_teleport_id: i32,
    pub play_destroy_entities_id: i32,
    pub play_chunk_data_id: i32,
    pub play_map_chunk_bulk_id: i32,
    pub play_multi_block_change_id: i32,
    pub play_block_change_id: i32,
    pub play_plugin_message_id: i32,
    pub play_custom_payload_id: i32,
}

