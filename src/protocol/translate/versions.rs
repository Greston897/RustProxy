/// Получить информацию о версии по протоколу.
pub fn version_info(protocol: i32) -> &'static ProtocolVersion {
    ALL_VERSIONS
        .iter()
        .find(|v| v.id.0 == protocol)
        .unwrap_or_else(|| {
            // Фолбэк на ближайшую поддерживаемую версию
            ALL_VERSIONS.iter().find(|v| v.id.0 == 777).unwrap()
        })
}

/// Проверить, поддерживается ли протокол.
pub fn is_supported(protocol: i32) -> bool {
    ALL_VERSIONS.iter().any(|v| v.id.0 == protocol)
}
